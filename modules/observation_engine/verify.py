        for name, replacements, probe, expected_failure in cli_mutations:
            with tempfile.TemporaryDirectory(prefix="mutant-" + name + "-", dir=scratch) as td:
                require(Path(td).resolve().parent == scratch, "temporary copy escaped scratch")
