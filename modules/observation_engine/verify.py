                shutil.copytree(ROOT, target, ignore=shutil.ignore_patterns(".git"))
                source = target / "Main.lean"
                body = source.read_text(encoding="utf-8")
                for old, new, count in replacements:
                    require(body.count(old) == count, name + ": wrong mutation site count")
                    body = body.replace(old, new)
                source.write_text(body, encoding="utf-8")
                run([args.lake, "env", "lean", "-j", "1", "Main.lean"], cwd=target, label=name + "-compile")
                cli_command = [args.lake, "env", "lean", "-j", "1", "--run", "Main.lean"]
